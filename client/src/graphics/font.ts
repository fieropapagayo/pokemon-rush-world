function sheet(chars: string, gw: number, gh: number, bit: (ch: string, x: number, y: number) => boolean, perRow: number) {
  const cw = gw + 2, chh = gh + 2;
  const rows = Math.ceil(chars.length / perRow);
  const c = document.createElement('canvas'); c.width = cw * perRow; c.height = chh * rows;
  const ctx = c.getContext('2d')!;
  const img = ctx.createImageData(c.width, c.height);
  const put = (x: number, y: number, r: number, g: number, b: number) => { const i = (y * c.width + x) * 4; img.data[i] = r; img.data[i + 1] = g; img.data[i + 2] = b; img.data[i + 3] = 255; };
  [...chars].forEach((ch, idx) => {
    const ox = (idx % perRow) * cw, oy = Math.floor(idx / perRow) * chh;
    // contorno
    for (let y = 0; y < gh; y++) for (let x = 0; x < gw; x++) if (bit(ch, x, y)) {
      for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) {
        if (Math.abs(dx) + Math.abs(dy) !== 1) continue;
        put(ox + 1 + x + dx, oy + 1 + y + dy, 20, 14, 28);
      }
    }
    for (let y = 0; y < gh; y++) for (let x = 0; x < gw; x++) if (bit(ch, x, y)) put(ox + 1 + x, oy + 1 + y, 255, 255, 255);
  });
  ctx.putImageData(img, 0, 0);
  return { canvas: c, cw, chh, perRow };
}

export function font3Sheet() {
  return sheet(FONT3_CHARS, 3, 5, (ch, x, y) => G3[ch][y * 3 + x] === '1', 16);
}
export function font5Sheet() {
  return sheet(FONT5_CHARS, 5, 7, (ch, x, y) => G5[ch][y][x] === '1', 16);
}

const ACC: Record<string, string> = { 'Á': 'A', 'É': 'E', 'Í': 'I', 'Ó': 'O', 'Ú': 'U', 'Ü': 'U', 'À': 'A', 'È': 'E', 'Ì': 'I', 'Ò': 'O', 'Ù': 'U', '✦': '*', '₽': 'P' };
/** Normaliza un texto a los glifos disponibles en la fuente 3x5. */
export function f3(s: string) {
  let o = '';
  for (const ch of s.toUpperCase()) { const m = ACC[ch] ?? ch; o += G3[m] ? m : '?'; }
  return o;
}
