export const FAMILIES: Record<string, string[]> = (() => {
  const f: Record<string, string[]> = {};
  for (const sp of SPECIES_LIST) (f[sp.family] ||= []).push(sp.key);
  for (const k in f) f[k].sort((a, b) => SPECIES[a].stage - SPECIES[b].stage);
  return f;
})();

export function speciesBaseExp(sp: SpeciesDef) {
  const t = sp.base.hp + sp.base.atk + sp.base.def + sp.base.spd;
  return Math.round(t * t / 600);
}
